use crate::crypto::sha256::Sha256;

const B: usize = 64;
const I: u8 = 0x36;
const O: u8 = 0x5c;

fn hmac_sha256(key: &[u8], message: &[u8]) -> [u8; 32] {
    let mut k_prime = [0u8; B];
    let mut i_pad = [I; B];
    let mut o_pad = [O; B];

    if key.len() > B {
        k_prime[..32].copy_from_slice(&Sha256::hash(key));
    } else {
        k_prime[..key.len()].copy_from_slice(key);
    }

    for n in 0..B {
        i_pad[n] = i_pad[n] ^ k_prime[n];
        o_pad[n] = o_pad[n] ^ k_prime[n];
    }

    let mut hasher = Sha256::new();
    hasher.update(&i_pad);
    hasher.update(message);
    let inner = hasher.finalize();

    hasher = Sha256::new();
    hasher.update(&o_pad);
    hasher.update(&inner);
    hasher.finalize()
}

